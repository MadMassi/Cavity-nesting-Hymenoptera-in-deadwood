# First, transform and scale variables. Each SEM node is scaled once using
# its designated reference population, rather than being rescaled separately
# in every component model. This keeps a given node in the same units along
# all incoming and outgoing pathways.
sem_gauss <- sem_data %>%
  mutate(
    tr_prate = if_else(
      host_abund_tot > 0,
      qlogis((par_abund + 0.5) / (host_abund_tot + 1)),
      NA_real_
