combine_contrast_info <- function(
  response,
  response_specific_contrast,
  gaussian_contrast
) {
  response_specific <- as.data.frame(response_specific_contrast)
  gaussian <- as.data.frame(gaussian_contrast)

  if (!identical(response_specific$contrast, gaussian$contrast)) {
    stop("Response-specific and Gaussian treatment contrasts do not match.")
  }

  data.frame(
    Response = response,
    Contrast = response_specific$contrast,
    Response_specific_estimate = response_specific$estimate,
    Response_specific_SE = response_specific$SE,
    Response_specific_df = response_specific$df,
    Response_specific_test_statistic = response_specific$z.ratio,
    Response_specific_P = response_specific$p.value,
    Gaussian_estimate = gaussian$estimate,
    Gaussian_SE = gaussian$SE,
    Gaussian_df = gaussian$df,
    Gaussian_test_statistic = gaussian$z.ratio,
    Gaussian_P = gaussian$p.value,
    check.names = FALSE
  )
}

