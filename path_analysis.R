#### > 5.1 Response-specific path analysis ####
# Response-specific component models
# Standardized response-scale average marginal effects are calculated manually

# Apparent-parasitism component model. This mirrors the predictor and
# random-effect structure of p_modd in deadwd_script.R, but uses the
# bounded apparent-parasitism rate required by beta regression.
prt_sem <- glmmTMB(
  p_rate2 ~ treatment + mc_imp + ant_pres_num +
    par_rich + host_rich + log_tr + cnpy_prop +
    (1 | site/plot_id),
  data = sem_data_p,
  family = beta_family(link = "logit")
)

# Parasitoid-richness component model. Parasitoid abundance is omitted
# both as a response and as a predictor because it is strongly correlated
# with parasitoid richness.
pr_sem <- glm(
  par_rich ~ treatment + host_rich + log_hatot + ant_pres_num + mc_imp +
    log_tr + cnpy_prop,
  data = sem_data_p,
  family = poisson()
)

# Host-richness component model.
hr_sem <- glmmTMB(
  host_rich ~ treatment + mc_imp + log_tr + cnpy_prop +
    log_hatot +
    (1 | plot_id),
  data = sem_data,
  family = genpois()
)

# Total-host-abundance component model. Total host abundance includes
# both successfully emerged hosts and hosts from which parasitoids emerged.
ha_sem <- glmmTMB(
  log_hatot ~ treatment + log_tr + mc_imp + ant_pres_num +
    cnpy_prop +
    (1 | site/plot_id),
  data = sem_data,
  ziformula = ~ site + treatment,
  family = ziGamma(link = "log")
)

# Moisture-content component model.
mc_sem <- glmmTMB(
  mc_imp ~ treatment + log_tr + cnpy_prop +
    (1 | site/plot_id),
  data = sem_data_mc,
  dispformula = ~ site + treatment,
  family = beta_family()
)

# Ant-occurrence component model.
ant_sem <- glmmTMB(
  ant_pres_num ~ treatment + log_tr + cnpy_prop +
    (1 | site/plot_id),
  data = sem_data,
  family = binomial()
)

# Canopy cover is measured at plot level, so retain one row per plot for
# this component rather than repeating the same response for every trap.
cnpy_sem <- glmmTMB(
  cnpy_prop ~ log_tr +
    (1 | site),
  data = sem_data_plot,
  family = gaussian(link = "identity")
