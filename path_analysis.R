    tr_logtr = log_tr,
    tr_cnpy = cnpy_prop
  )

# Standardize a variable using the mean and SD from a specified reference
# population while applying those same constants to every observation.
scale_from_reference <- function(x, reference) {
  reference_mean <- mean(reference, na.rm = TRUE)
  reference_sd <- sd(reference, na.rm = TRUE)

  if (!is.finite(reference_sd) || reference_sd == 0) {
    stop("Reference SD must be finite and greater than zero.")
  }

  as.numeric((x - reference_mean) / reference_sd)
}

parasitoid_reference <- sem_gauss$host_abund_tot > 0
plot_reference <- !duplicated(sem_gauss$plot_id)

# Parasitoid nodes are defined for traps with evidence of host brood.
sem_gauss$z_prate <- scale_from_reference(
  sem_gauss$tr_prate,
  sem_gauss$tr_prate[parasitoid_reference]
)
sem_gauss$z_par_rich <- scale_from_reference(
  sem_gauss$tr_par_rich,
  sem_gauss$tr_par_rich[parasitoid_reference]
)

# Host and moisture nodes use the complete trap-level reference population.
