# Calculate standardized response-scale effects for every continuous
# predictor in the component models. Factors and binary variables are omitted.
sem_model_list <- sem_mods[
  vapply(
    sem_mods,
    function(x) inherits(x, c("glm", "lm", "glmmTMB")),
    logical(1)
  )
]

standardized_paths <- do.call(
  rbind,
  lapply(names(sem_model_list), function(model_name) {
    model <- sem_model_list[[model_name]]
    dat <- model.frame(model)

    variables <- all.vars(lme4::nobars(formula(model)))
    predictors <- setdiff(variables, variables[1])

    continuous_predictors <- predictors[
      vapply(
        predictors,
        function(x) {
          x %in% names(dat) &&
            is.numeric(dat[[x]]) &&
            dplyr::n_distinct(dat[[x]], na.rm = TRUE) > 2
        },
        logical(1)
      )
    ]

    results <- lapply(
      continuous_predictors,
      function(x) standardized_path(model, x)
    )

    result <- do.call(rbind, results)
    result$Model <- model_name
    result
  })
)

rownames(standardized_paths) <- NULL
