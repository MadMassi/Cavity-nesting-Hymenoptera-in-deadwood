chao_sample_coverage <- function(x) {
  x <- x[x > 0]
  n  <- sum(x)
  if (n == 0) return(NA_real_)
  f1 <- sum(x == 1)
  f2 <- sum(x == 2)
  if (f1 == 0) return(1)
  if (f2 > 0) {
    1 - (f1 / n) * ((n - 1) * f1 / ((n - 1) * f1 + 2 * f2))
  } else {
    1 - (f1 / n) * ((n - 1) * (f1 - 1) / ((n - 1) * (f1 - 1) + 2))
  }
}

