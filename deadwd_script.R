extract_model_table_results <- function(model_list) {
  metadata <- bind_rows(lapply(names(model_list), function(model_name) {
    model <- model_list[[model_name]]
    model_family <- family(model)
    data.frame(
      model = model_name,
      family = model_family$family,
      link = model_family$link,
      observations = nobs(model),
      logLik = as.numeric(logLik(model)),
      AIC = AIC(model),
      stringsAsFactors = FALSE
    )
  }))

  fixed <- bind_rows(lapply(names(model_list), function(model_name) {
    tidy(model_list[[model_name]], effects = "fixed", conf.int = TRUE) %>%
      mutate(model = model_name, .before = 1)
  }))

  random <- bind_rows(lapply(names(model_list), function(model_name) {
    random_terms <- tryCatch(
      tidy(model_list[[model_name]], effects = "ran_pars"),
      error = function(e) data.frame()
    )
    if (nrow(random_terms) > 0) {
      random_terms <- random_terms %>%
        mutate(model = model_name, .before = 1)
    }
    random_terms
  }))

  list(metadata = metadata, fixed = fixed, random = random)
}

