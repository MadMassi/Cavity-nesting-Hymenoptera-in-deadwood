# function to scale  variables within-treatment
scale_within_treatment <- function(df, name_map, tr_var = "treatment") {
  
  for (old in names(name_map)) {
    new <- name_map[[old]]
    df[[new]] <- NA_real_
    
    for (tr in unique(df[[tr_var]])) {
      idx <- df[[tr_var]] == tr
      x   <- df[[old]][idx]
      
      if (sd(x, na.rm = TRUE) == 0) {
        df[[new]][idx] <- 0
      } else {
        df[[new]][idx] <- as.numeric(scale(x))
      }
    }
  }
  
  df
}

